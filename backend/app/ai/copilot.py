from app.ai.gemini_client import gemini_client


class Copilot:
    def answer(self, message: str, snapshot: dict) -> dict:
        if gemini_client.is_configured():
            return self._gemini_answer(message, snapshot)
        return self._offline_answer(message, snapshot)

    def _offline_answer(self, message: str, snapshot: dict) -> dict:
        routers = snapshot["routers"]
        alerts = snapshot["alerts"]
        predictions = snapshot["predictions"]
        lower = message.lower()
        riskiest = predictions[0]
        router = next(r for r in routers if r["router_id"] == riskiest["router_id"])

        requested_router = next((r for r in routers if r["router_id"].lower() in lower), router)
        evidence = [
            f"{requested_router['router_id']} CPU {requested_router['cpu']:.1f}%, memory {requested_router['memory']:.1f}%",
            f"Latency {requested_router['latency']:.1f} ms, packet loss {requested_router['packet_loss']:.2f}%",
            f"Bandwidth {requested_router['bandwidth']:.1f}%, link {requested_router['link_status']}",
        ]

        if "summarize" in lower or "incident" in lower:
            critical = [a for a in alerts if a["severity"] == "critical"]
            return {
                "analysis": f"{len(alerts)} recent alerts are active, including {len(critical)} critical events.",
                "explanation": "The incident stream is dominated by congestion, packet loss, latency, and link-state symptoms generated by the MPLS simulator.",
                "recommendations": [
                    "Prioritize critical routers by risk score.",
                    "Confirm whether packet loss aligns with bandwidth saturation before taking service action.",
                    "Export the incident report for NOC handover.",
                ],
                "evidence": [a["message"] for a in alerts[:4]] or ["No active incidents in the current window."],
            }

        if "most likely" in lower or "fail" in lower:
            return {
                "analysis": f"{riskiest['router_id']} is currently most likely to fail.",
                "explanation": f"The model assigns a {riskiest['failure_probability'] * 100:.1f}% critical probability and risk score {riskiest['risk_score']:.1f}. {router['root_cause']}",
                "recommendations": router["recommendations"],
                "evidence": evidence,
            }

        if "packet loss" in lower:
            impacted = sorted(routers, key=lambda item: item["packet_loss"], reverse=True)[:3]
            return {
                "analysis": f"Highest packet loss is on {impacted[0]['router_id']} at {impacted[0]['packet_loss']:.2f}%.",
                "explanation": "Packet loss in this simulation usually follows congestion, link instability, or CPU saturation.",
                "recommendations": [
                    "Check interface drops and QoS queues on the impacted path.",
                    "Temporarily re-route priority traffic over the secondary LSP.",
                    "Correlate loss with bandwidth utilization and latency trends.",
                ],
                "evidence": [f"{r['router_id']}: {r['packet_loss']:.2f}% loss, {r['bandwidth']:.1f}% bandwidth" for r in impacted],
            }

        return {
            "analysis": f"{requested_router['router_id']} is {requested_router['status']} with {requested_router['severity']} severity.",
            "explanation": requested_router["root_cause"],
            "recommendations": requested_router["recommendations"],
            "evidence": evidence,
        }

    def _gemini_answer(self, message: str, snapshot: dict) -> dict:
        import json
        prompt = (
            f"You are a senior network engineer and AI copilot for secure MPLS operations. "
            f"You have the following network telemetry snapshot: {snapshot}.\n"
            f"User asks: '{message}'\n"
            f"Provide a helpful answer. Respond ONLY with a JSON object containing keys: "
            f"'analysis', 'explanation', 'recommendations', and 'evidence'."
        )
        try:
            text = gemini_client.generate(prompt)
            data = json.loads(text)
            return {
                "analysis": data.get("analysis", "No analysis provided."),
                "explanation": data.get("explanation", "No explanation provided."),
                "recommendations": data.get("recommendations", []),
                "evidence": data.get("evidence", []),
            }
        except Exception as e:
            fallback = self._offline_answer(message, snapshot)
            fallback["analysis"] = f"[Gemini Fallback: {e}] " + fallback["analysis"]
            return fallback



copilot = Copilot()
